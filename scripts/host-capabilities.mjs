// Generates docker-compose.host-caps.yml: bind-mounts for every host
// capability (absolute path) referenced by ~/.dsh cordis patches, so those
// references resolve verbatim inside the container. Runs on the HOST before
// `docker compose up` (npm run docker:up); the file is regenerated on every
// start, so newly registered host runtimes are discovered automatically —
// no hand-edited volume lines.
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { homedir } from 'node:os'
import { pathToFileURL } from 'node:url'
import { extractHostRefs } from './doctor.mjs'
import { resolveConfig } from '../src/config.js'

// Directories the container image itself owns or populates. A capability
// mount must never shadow one of these (host /usr/bin over the image's
// binaries would break the runtime). Deeper mount points are fine: binding
// host /usr/local/lib/node_modules/<pkg> only shadows a path the image does
// not define.
const CONTAINER_CRITICAL = new Set([
  '/usr', '/usr/bin', '/usr/sbin', '/usr/lib', '/usr/lib64',
  '/usr/local', '/usr/local/bin', '/usr/local/lib',
  '/etc', '/var', '/bin', '/sbin', '/lib', '/lib64',
  '/opt', '/run', '/tmp', '/root', '/home', '/srv', '/mnt', '/media',
  '/boot', '/dev', '/proc', '/sys',
])

// Mount root for one host reference.
// - inside the host home: the first-level tree under the home (e.g.
//   ~/.taptap-maker) so version bumps inside the tree keep resolving;
// - outside the home: the reference's own directory (read-only upstream).
// Returns null when no safe root exists (system directories, degenerate
// paths) — the caller reports those as skipped instead of mounting.
export function capabilityRoot(ref, home) {
  ref = resolve(ref)
  home = resolve(home)
  if (ref === '/' || ref === home) return null
  if (ref.startsWith(home + '/')) {
    const seg = ref.slice(home.length + 1).split('/')[0]
    if (!seg || seg === '.') return null
    return { root: join(home, seg), kind: 'home' }
  }
  const dir = dirname(ref)
  if (dir === '/' || CONTAINER_CRITICAL.has(dir)) return null
  return { root: dir, kind: 'external' }
}

const mountsFor = (roots, home) => roots.flatMap(root => root.kind === 'home'
  ? [
    { source: root.root, target: root.root, mode: 'rw' },
    { source: root.root, target: join('/home/node', root.root.slice(home.length + 1)), mode: 'rw' },
  ]
  : [{ source: root.root, target: root.root, mode: 'ro' }])

// Derive the full mount plan from raw references. Pure: no filesystem
// access, deterministic order. Home trees are mounted twice — at their own
// path (so patch references resolve verbatim) and under /home/node (so
// runtimes that locate data via os.homedir() find it), both writable since
// capability trees usually carry refreshable auth state.
export function planCapabilityMounts(refs, home) {
  home = resolve(home)
  const roots = []
  const byRoot = new Map()
  const skipped = []
  for (const ref of refs) {
    const plan = capabilityRoot(ref, home)
    if (!plan) {
      skipped.push({ ref, reason: 'no safe mount root (system directory or degenerate path)' })
      continue
    }
    const existing = byRoot.get(plan.root)
    if (existing) {
      existing.refs.push(ref)
      continue
    }
    const entry = { ...plan, refs: [ref] }
    byRoot.set(plan.root, entry)
    roots.push(entry)
  }
  return { roots, mounts: mountsFor(roots, home), skipped }
}

const renderYAML = (roots, mounts, skipped, patchFiles) => {
  const lines = [
    '# AUTO-GENERATED by scripts/host-capabilities.mjs — do not edit by hand.',
    '# Host capability bridge: absolute paths referenced by dsh patches,',
    '# bind-mounted so they resolve verbatim inside the container.',
    `# Scanned: ${patchFiles.join(', ')}`,
    '# Regenerate with: npm run docker:up',
    'services:',
    '  dsh-team:',
  ]
  if (roots.length === 0 && skipped.length === 0) {
    lines.push('    volumes: []  # no host capabilities referenced')
  } else {
    lines.push('    volumes:')
    for (const root of roots) {
      const mode = root.kind === 'home'
        ? `home tree, rw, also visible under /home/node (${root.refs.length} ref${root.refs.length === 1 ? '' : 's'})`
        : `external directory, read-only (${root.refs.length} ref${root.refs.length === 1 ? '' : 's'})`
      lines.push(`      # ${root.root} — ${mode}`)
      for (const ref of root.refs) lines.push(`      #   ${ref}`)
    }
    for (const mount of mounts) {
      lines.push(`      - "${mount.source}:${mount.target}${mount.mode === 'ro' ? ':ro' : ''}"`)
    }
    for (const skip of skipped) lines.push(`      # SKIPPED ${skip.ref} — ${skip.reason}`)
  }
  return lines.join('\n') + '\n'
}

function main() {
  const config = resolveConfig()
  const home = homedir()
  // The container loads the global patch plus exactly one profile; bridging
  // references from profiles it never activates would be dead weight (and
  // can block startup, e.g. paths outside Docker Desktop's shared roots).
  const profile = process.env.DSH_TEAM_PROFILE || 'team-bots'
  const patchFiles = [
    join(config.dshHome, 'cordis.patch.yml'),
    join(config.dshHome, 'profiles', profile, 'cordis.patch.yml'),
  ]
  const scanned = patchFiles.filter(existsSync)
  const refs = []
  for (const file of scanned) {
    for (const ref of extractHostRefs(readFileSync(file, 'utf8'))) {
      if (!refs.includes(ref)) refs.push(ref)
    }
  }

  const plan = planCapabilityMounts(refs, home)
  // Roots that do not exist on this host cannot be mounted; doctor reports
  // them as MISSING against the patch itself.
  const roots = []
  const skipped = [...plan.skipped]
  for (const root of plan.roots) {
    if (existsSync(root.root)) {
      roots.push(root)
    } else {
      skipped.push({ ref: root.root, reason: 'referenced tree does not exist on this host' })
    }
  }

  const outFile = resolve('docker-compose.host-caps.yml')
  const mounts = mountsFor(roots, resolve(home))
  const yaml = renderYAML(roots, mounts, skipped, scanned)
  const previous = existsSync(outFile) ? readFileSync(outFile, 'utf8') : null
  if (previous !== yaml) {
    writeFileSync(outFile, yaml)
    console.log(`wrote ${outFile}`)
  } else {
    console.log(`${outFile} unchanged`)
  }

  console.log(`profile     ${profile}`)
  console.log(`scanned ${scanned.length} patch file(s): ${scanned.join(', ') || 'none'}`)
  if (refs.length === 0) {
    console.log('no host capability references found')
  }
  for (const root of roots) {
    const view = root.kind === 'home' ? `same-path + /home/node/${root.root.slice(home.length + 1)}, rw` : 'same-path, ro'
    console.log(`capability  ${root.root}  (${root.refs.length} ref, ${view})`)
  }
  // Docker Desktop only bind-mounts sources inside its configured File
  // Sharing paths; warn (don't skip) when a root falls outside the defaults.
  if (process.platform === 'darwin') {
    const sharedPrefixes = ['/Users/', '/Volumes/', '/private/', '/tmp/', '/var/folders/']
    for (const root of roots) {
      if (!sharedPrefixes.some(prefix => root.root.startsWith(prefix))) {
        console.log(`WARNING     ${root.root} is outside Docker Desktop's default File Sharing paths; add it under Docker → Settings → Resources → File Sharing, or remove the reference`)
      }
    }
  }
  for (const skip of skipped) {
    console.log(`SKIPPED     ${skip.ref}  — ${skip.reason}`)
  }
  console.log(`next: npm run docker:up  (docker compose -f docker-compose.yml -f docker-compose.host-caps.yml up -d --build)`)
}

const invokedDirectly = process.argv[1]
  && import.meta.url === pathToFileURL(resolve(process.argv[1])).href
if (invokedDirectly) main()
